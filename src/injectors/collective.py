"""
Collective anomalies (Section 3.2): bursts and shilling, shared by the three
corrupted signals.

  * Burst    -> concentration in time: many records reach the same target items
               within a short window, regardless of which accounts produce them
               (existing users or fake users). Timing is controlled.
  * Shilling -> concentration across accounts: a group of coordinated fake
               profiles, generated by a common attack strategy, targets the same
               items in the same direction (push / nuke). Filler items, chosen by
               the attack model (random, popular, segment), make each profile
               plausible in isolation. No constraint on timing.
"""

from __future__ import annotations

import math

import numpy as np

from injectors.base import ADD, COLLECTIVE, Perturbation, TemporalSampler, _resolve_size, _sample_excluding
from injectors.text_generation import format_prompt
from utils import ITEM, RATING, USER, snap_to_scale


class BurstPerturbation(Perturbation):
    observability = COLLECTIVE
    operation = ADD
    default_target = "item"
    generate_reviews = False

    BURST_DEFAULTS = {
        "selection_strategy": "top",
        "min_per_node": 10,
        "max_per_node": 50,
        "item_choice": "uniform",            # target=user: how the burst items are chosen
        "rating_behavior": {"min_rating": None, "max_rating": None, "sampling_strategy": "uniform"},
        "temporal_behavior": {"start_timestamp": None, "end_timestamp": None,
                              "window": {"days": 1, "hours": 0, "minutes": 0}},
        "fake_users": {"use_fake_users": True, "fake_behavior": "random", "filler_size": 0},
    }

    def burst_ratings(self, n: int, node) -> list:
        if not self.ctx.has_rating:
            return [None] * n
        ref = self._ref_ratings.get(node)
        return list(self.sample_rating_values(n, ref))

    def burst_prompt(self, item, rating) -> dict:
        return {}

    def perturb(self, df):
        ctx, rng = self.ctx, self.rng
        self._ref_ratings = ctx.ratings_of(self.target_col)
        sampler = self.temporal_sampler()
        fake = self.use_fake_users() and self.target_col == ITEM
        item_users = ctx.item_users(df)
        user_items = ctx.user_items(df) if self.target_col == USER else {}
        items_pool = ctx.item_pop.index.to_numpy()
        pop_probs = ctx.item_pop.to_numpy(dtype=float) / ctx.item_pop.sum()

        targets, fillers, requests = [], [], []
        for node, n in self.plan_additions(df):
            if self.target_col == ITEM:
                users = [self.new_fake_user() for _ in range(n)] if fake \
                    else self.existing_producers(node, n, item_users)
                items = [node] * len(users)
            else:   # the target user produces a burst of interactions
                probs = pop_probs if self.p.get("item_choice") == "popular" else None
                items = list(_sample_excluding(items_pool, n, user_items.get(node, set()), rng, probs))
                users = [node] * len(items)
            times = sampler.sample(len(items))
            ratings = self.burst_ratings(len(items), node)
            for u, it, t, r in zip(users, items, times, ratings):
                targets.append(self.new_record(u, it, t, r))
                if self.generate_reviews:
                    requests.append(self.burst_prompt(it, r))
                if fake:
                    fillers.extend(self.filler_records(u, exclude={it}))

        if self.generate_reviews and requests:
            for rec, txt in zip(targets, self.generate_texts(requests)):
                rec["review_text"] = txt
        self.stats["targets"] = len({r[self.target_col] for r in targets})
        self.stats["fake_users"] = len(self.fake_users)
        df = self.append_records(df, targets, "target")
        return self.append_records(df, fillers, "filler")


class ShillingPerturbation(Perturbation):
    observability = COLLECTIVE
    operation = ADD
    default_target = "item"
    generate_reviews = False

    SHILLING_DEFAULTS = {
        "selection_strategy": "uniform",
        "num_targets": 1,                    # target items shared by the whole group
        "direction": "push",                 # push | nuke
        "filler_strategy": "random",         # random | popular | segment
        "filler_size": 20,                   # int, [min, max] or fraction of the catalogue
        "popular_pool": 0.1,                 # popular fillers: top fraction (or number) of items
        "segment_items": None,               # segment fillers: explicit list (else same category)
        # no timing constraint: records are spread over this interval (dataset range by default)
        "temporal_behavior": {"start_timestamp": None, "end_timestamp": None},
    }

    # ------------------------------------------------------------ items
    def filler_items(self, strategy: str, n: int, exclude: set, targets: list) -> np.ndarray:
        ctx = self.ctx
        if strategy == "random":
            pool = ctx.item_pop.index.to_numpy()
        elif strategy == "popular":
            k = _resolve_size(self.p.get("popular_pool", 0.1), len(ctx.item_pop), self.rng)
            pool = ctx.item_pop.index.to_numpy()[:max(k, n + len(exclude))]
        elif strategy == "segment":
            pool = self.segment_pool(targets)
        else:
            raise ValueError(f"[{self.name}] unknown filler_strategy '{strategy}'")
        return _sample_excluding(pool, n, exclude, self.rng)

    def segment_pool(self, targets) -> np.ndarray:
        seg = self.p.get("segment_items")
        if seg:
            return np.array([str(s) for s in seg])
        if self.ctx.category is None:
            raise ValueError(f"[{self.name}] segment fillers need item categories "
                             "(input.items in data.yaml) or an explicit 'segment_items' list")
        cats = {self.ctx.category.get(t) for t in targets} - {None}
        return np.array([i for i, c in self.ctx.category.items() if c in cats and i in self.ctx.item_pop.index])

    # ---------------------------------------------------------- ratings
    def target_rating(self):
        return self.ctx.rmax if self.p.get("direction", "push") == "push" else self.ctx.rmin

    def global_rating_sample(self, n):
        r = self.ctx.reference[RATING].dropna().to_numpy(dtype=float)
        return snap_to_scale(self.rng.normal(r.mean(), r.std() or 1.0, n),
                             self.ctx.rmin, self.ctx.rmax, self.ctx.rstep)

    def item_rating_sample(self, items):
        stats = self._item_stats
        mu = np.array([stats.get(i, (self._gmean, self._gstd))[0] for i in items])
        sd = np.array([stats.get(i, (self._gmean, self._gstd))[1] for i in items])
        return snap_to_scale(self.rng.normal(mu, np.where(sd > 0, sd, 1.0)),
                             self.ctx.rmin, self.ctx.rmax, self.ctx.rstep)

    def profile_items_and_ratings(self, targets) -> tuple[list, list]:
        """Filler (and selected) items of one profile with their ratings. Overridden by rating shilling."""
        n = _resolve_size(self.p.get("filler_size", 20), len(self.ctx.item_pop), self.rng)
        items = list(self.filler_items(self.p.get("filler_strategy", "random"), n, set(targets), targets))
        ratings = list(self.item_rating_sample(items)) if self.ctx.has_rating else [None] * len(items)
        return items, ratings

    def target_prompt(self, item) -> dict:
        return {}

    # ---------------------------------------------------------------- run
    def perturb(self, df):
        ctx = self.ctx
        if ctx.has_rating:
            r = ctx.reference[RATING].dropna()
            self._gmean, self._gstd = float(r.mean()), float(r.std() or 1.0)
            g = ctx.reference.groupby(ITEM)[RATING]
            self._item_stats = {k: (m, s if np.isfinite(s) else self._gstd)
                                for k, m, s in zip(g.mean().index, g.mean().values, g.std().values)}
        k = int(self.p.get("num_targets", 1))
        targets = self.candidate_nodes(col=ITEM)[:k]
        if not targets or self.budget <= 0:
            return df
        n_profiles = max(1, math.floor(self.budget / len(targets)))
        tb = dict(self.p.get("temporal_behavior") or {})
        tb["window"] = 0                                  # shilling imposes no timing constraint
        sampler = TemporalSampler(tb, ctx, self.rng)
        reviews = self._item_reviews()

        target_recs, filler_recs, requests = [], [], []
        for _ in range(n_profiles):
            uid = self.new_fake_user()
            for t in targets:
                target_recs.append(self.new_record(uid, t, sampler.sample(1)[0],
                                                   self.target_rating() if ctx.has_rating else None))
                if self.generate_reviews:
                    requests.append(self.target_prompt(t))
            items, ratings = self.profile_items_and_ratings(targets)
            for it, r, ts in zip(items, ratings, sampler.sample(len(items))):
                rv = reviews.get(it)
                filler_recs.append(self.new_record(uid, it, ts, r,
                                                   str(self.rng.choice(rv)) if rv else None))
        if self.generate_reviews and requests:
            for rec, txt in zip(target_recs, self.generate_texts(requests)):
                rec["review_text"] = txt
        self.stats.update({"targets": len(targets), "target_items": targets, "fake_users": n_profiles})
        df = self.append_records(df, target_recs, "target")
        return self.append_records(df, filler_recs, "filler")


def prompt_request(template: str, ctx, item=None, rating=None, review=None, polarity=None, kind="review"):
    """Fill the placeholders of a prompt ({title}, {category}, {item}, {rating}, {review}, {polarity})."""
    title = (ctx.title or {}).get(item) if item is not None else None
    category = (ctx.category or {}).get(item) if item is not None else None
    if polarity is None and rating is not None:
        polarity = ctx.polarity(rating)
    values = {"item": title or category or "this product", "title": title or "this product",
              "category": category or "product", "rating": "" if rating is None else rating,
              "review": review or "", "polarity": polarity or ""}
    return {"prompt": format_prompt(template, values), "polarity": polarity, "kind": kind,
            "item": item, "rating": rating, "review": review}
